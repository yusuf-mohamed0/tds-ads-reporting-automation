#!/usr/bin/env python3
"""Discover Meta ad accounts and generate configs/clients.yaml.

Fetches every ad account the system-user token can see, keeps active ones,
groups accounts that clearly belong to the same owner (by normalized name),
and writes a generated clients config for review before promoting.

Usage:
  ./.venv/bin/python scripts/discover_clients.py [--output configs/clients.generated.yaml] [--include-inactive]
"""
import argparse
import os
import re
import sys
from collections import OrderedDict

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from facebook_business.api import FacebookAdsApi
from facebook_business.adobjects.user import User

DEFAULT_OUTPUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "configs", "clients.generated.yaml")

SUFFIX_RE = re.compile(r"\s*(ad account|ad-account|ads account)\s*$", re.IGNORECASE)
SLUG_RE = re.compile(r"[^a-z0-9]+")
STABLE = {
    "act_272954367455662": ("alamein-2022", "Alamein Outdoor Furniture"),
    "act_326559196172852": ("caravanserai", "Caravanserai"),
}

# Ad accounts that belong to the agency itself, not a billable client.
EXCLUDE_ACCOUNTS = {
    "act_562988774376657",  # Traffic (agency)
}


def load_token():
    env_path = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), ".env")
    env = open(env_path).read()
    m = re.search(r"^META_SYSTEM_USER_TOKEN=(.+)$", env, re.M)
    if not m:
        raise SystemExit("META_SYSTEM_USER_TOKEN not found in .env")
    return m.group(1).strip()


def base_name(name):
    return SUFFIX_RE.sub("", name).strip()


def slugify(name):
    slug = SLUG_RE.sub("-", base_name(name).lower()).strip("-")
    return slug or "client"


def discover(include_inactive=False):
    token = load_token()
    FacebookAdsApi.init(access_token=token)
    me = User(fbid="me")
    accounts = me.get_ad_accounts(
        fields=["name", "account_status", "currency", "timezone_name", "amount_spent"],
        params={"limit": 200},
    )
    active = [a for a in accounts if int(a.get("account_status", 1)) == 1]
    chosen = [a for a in (list(accounts) if include_inactive else active) if a["id"] not in EXCLUDE_ACCOUNTS]

    groups = OrderedDict()
    for acc in sorted(chosen, key=lambda a: base_name(a.get("name", "")).lower()):
        acc_id = acc["id"]
        if acc_id in STABLE:
            key = STABLE[acc_id][0]
        else:
            key = slugify(base_name(acc.get("name", "")))
        groups.setdefault(
            key,
            {
                "id": key,
                "name": base_name(acc.get("name", "")).title(),
                "accounts": [],
                "currency": acc.get("currency", "EGP"),
                "timezone": acc.get("timezone_name", "Africa/Cairo"),
                "statuses": set(),
            },
        )
        g = groups[key]
        g["accounts"].append(acc)
        g["statuses"].add(int(acc.get("account_status", 1)))
        if acc_id in STABLE:
            g["id"], g["name"] = STABLE[acc_id]

    lines = ["# Generated by scripts/discover_clients.py", "# Review and promote to configs/clients.yaml when happy.", "clients:"]
    for g in groups.values():
        lines.append("  - id: %s" % g["id"])
        lines.append('    name: "%s"' % g["name"])
        lines.append('    report_recipient: "reports@trafficdigitalsolutions.com"')
        lines.append('    language: "en"')
        lines.append('    currency: "%s"' % g["currency"])
        lines.append('    timezone: "%s"' % g["timezone"])
        lines.append("    goals:")
        lines.append('      primary: "leads"')
        lines.append("      secondary:")
        lines.append('        - "traffic"')
        lines.append("    meta:")
        lines.append("      enabled: true")
        lines.append("      ad_accounts:")
        for acc in g["accounts"]:
            status = int(acc.get("account_status", 1))
            note = "  # status=%d" % status if status != 1 else ""
            lines.append('        - id: "%s"%s' % (acc["id"], note))
            lines.append('          label: "%s"' % acc.get("name", ""))
        lines.append("      conversion_actions: {}")
        lines.append("    report:")
        lines.append("      include_sections:")
        lines.append('        - "executive_summary"')
        lines.append('        - "overall_performance"')
        lines.append('        - "meta_ads"')
        lines.append('        - "campaign_breakdown"')
        lines.append('        - "recommendations"')
        lines.append("      notes:")
        lines.append('        account_manager: "Traffic Digital Solutions"')
    return "\n".join(lines) + "\n", groups


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--output", default=DEFAULT_OUTPUT)
    ap.add_argument("--include-inactive", action="store_true")
    args = ap.parse_args()
    body, groups = discover(include_inactive=args.include_inactive)
    os.makedirs(os.path.dirname(args.output), exist_ok=True)
    with open(args.output, "w") as fh:
        fh.write(body)
    print("Wrote %s (%d client groups)" % (args.output, len(groups)))
    for g in groups.values():
        extra = ["act_%s" % a["id"] for a in g["accounts"][1:]]
        print("- %-28s %s%s" % (g["name"], ",".join(a["id"] for a in g["accounts"]), ("  [INACTIVE]" if any(s != 1 for s in g["statuses"]) else "")))


if __name__ == "__main__":
    main()
